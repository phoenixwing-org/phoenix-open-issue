/** 各页帮助内容 */
export type PageHelpContent = {
  title: string;
  bullets: string[];
  /** 可选：本页巡游步骤 */
  tourSteps?: DriveStep[];
};

function step(
  selector: string,
  title: string,
  description: string,
  side: "top" | "right" | "bottom" | "left" = "bottom",
): DriveStep {
  return {
    element: selector,
    popover: { title, description, side, align: "start" },
  };
}

